/**
 * Small DSP helpers shared by the audio modules. Work on any BaseAudioContext.
 */
export const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
export const lerp = (a, b, t) => a + (b - a) * t;
export const mtof = (m) => 440 * Math.pow(2, (m - 69) / 12);

/** Deterministic PRNG (mulberry32). */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Module-level seeded random (reproducible noise, offsets and jitter). Reseeded by AudioEngine. */
let _rand = null;
export function seedRandom(seed) { _rand = mulberry32(seed); }
export const rand = () => (_rand || (_rand = mulberry32(1))) ();

/** Mono noise buffer: 'white' | 'pink' | 'brown'. Built once and reused everywhere. */
export function makeNoiseBuffer(ctx, seconds = 4, kind = 'white') {
  const len = Math.floor(ctx.sampleRate * seconds);
  const buf = ctx.createBuffer(1, len, ctx.sampleRate);
  const d = buf.getChannelData(0);
  let b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0, last = 0;
  for (let i = 0; i < len; i++) {
    const w = rand() * 2 - 1;
    if (kind === 'pink') {
      b0 = 0.99886 * b0 + w * 0.0555179;
      b1 = 0.99332 * b1 + w * 0.0750759;
      b2 = 0.969 * b2 + w * 0.153852;
      b3 = 0.8665 * b3 + w * 0.3104856;
      b4 = 0.55 * b4 + w * 0.5329522;
      b5 = -0.7616 * b5 - w * 0.016898;
      d[i] = (b0 + b1 + b2 + b3 + b4 + b5 + b6 + w * 0.5362) * 0.11;
      b6 = w * 0.115926;
    } else if (kind === 'brown') {
      last = (last + 0.02 * w) / 1.02;
      d[i] = last * 3.5;
    } else {
      d[i] = w;
    }
  }
  return buf;
}

/** Stereo generated reverb impulse response: decaying noise that darkens over time. */
export function makeImpulse(ctx, seconds = 4.5, decay = 3.2, rng = Math.random) {
  const sr = ctx.sampleRate;
  const len = Math.floor(sr * seconds);
  const buf = ctx.createBuffer(2, len, sr);
  for (let ch = 0; ch < 2; ch++) {
    const d = buf.getChannelData(ch);
    let lp = 0;
    for (let i = 0; i < len; i++) {
      const t = i / len;
      const env = Math.pow(1 - t, decay);
      const coef = 0.55 - 0.47 * Math.sqrt(t); // one-pole low-pass: darker tail
      lp += ((rng() * 2 - 1) - lp) * coef;
      const fadeIn = Math.min(1, i / (sr * 0.02));
      d[i] = lp * env * fadeIn;
    }
  }
  return buf;
}
